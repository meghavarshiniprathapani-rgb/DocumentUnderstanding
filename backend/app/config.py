"""
Retrieva AI — Backend Configuration Module
Validated system settings via Pydantic Settings with immutable config version tracking.
"""

from functools import lru_cache
from typing import List, Literal

from pydantic import Field, field_validator
from pydantic_settings import BaseSettings, SettingsConfigDict


class Settings(BaseSettings):
    """
    Validated application configuration settings.
    Every output generated by the application or evaluation suite records `config_version`.
    """

    model_config = SettingsConfigDict(env_file=".env", env_file_encoding="utf-8", case_sensitive=False, extra="ignore")

    # Immutable Configuration Version String
    # MUST be recorded in every API response, log header, and evaluation output.
    config_version: str = Field(
        default="1.0.0", description="Semantic configuration version identifier recorded in all system outputs"
    )

    # Core Application Metadata
    app_name: str = Field(
        default="Retrieva AI Engine", description="Service name for OpenAPI documentation and discovery"
    )
    environment: Literal["development", "staging", "production", "test"] = Field(
        default="development", description="Runtime environment tier"
    )
    api_prefix: str = Field(default="/api/v1", description="Root URL prefix for REST endpoints")

    # Server Networking
    host: str = Field(default="0.0.0.0", description="Bind host address for Uvicorn server")
    port: int = Field(default=8000, ge=1024, le=65535, description="Network port for incoming HTTP traffic")

    # AI Pipeline & OCR Engine Defaults
    ocr_engine: Literal["layoutlmv3", "paddleocr", "tesseract"] = Field(
        default="layoutlmv3", description="Default document layout analysis and OCR engine"
    )
    vector_db: Literal["faiss", "chromadb", "qdrant"] = Field(
        default="faiss", description="Vector indexing engine for approximate nearest neighbor retrieval"
    )
    confidence_threshold: float = Field(
        default=0.85, ge=0.0, le=1.0, description="Minimum confidence threshold for bounding box extraction"
    )

    # File Ingestion Constraints
    max_upload_size_mb: int = Field(default=50, gt=0, le=500, description="Maximum PDF upload size in megabytes")
    max_pages_per_document: int = Field(default=100, gt=0, le=1000, description="Maximum allowed pages per document")
    config_id: str = Field(default="O3-v1.0.0", description="Configuration identifier recorded in all provenance records")

    # Cross-Origin Resource Sharing (CORS)
    cors_origins: List[str] = Field(
        default=[
            "http://localhost:5173",
            "http://127.0.0.1:5173",
            "http://localhost:4173",
            "http://localhost:3000",
            "http://127.0.0.1:3000",
        ],
        description="List of allowed CORS origins for web client communication",
    )

    @field_validator("config_version")
    @classmethod
    def validate_config_version(cls, v: str) -> str:
        if not v or not v.strip():
            raise ValueError("config_version cannot be empty")
        return v.strip()


@lru_cache(maxsize=1)
def get_settings() -> Settings:
    """
    Returns cached, validated singleton Settings instance.
    """
    return Settings()
