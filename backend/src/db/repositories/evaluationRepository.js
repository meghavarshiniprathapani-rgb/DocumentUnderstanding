/**
 * Retrieva AI — Evaluation Repository (AIML-59 / M1.5 / M1.5.3)
 * 
 * Provides persistence and retrieval for benchmark evaluation runs and KPI tracking:
 * - Preserves config_hash, model_versions, split, dataset_split_hash, acceptance_hash, and KPI telemetry.
 * - Protects charter KPIs and frozen baseline evidence from out-of-band corruption.
 * - Deterministic ordering for audit tracking and historical KPI regression comparisons.
 */

import { query, sanitizeError } from '../pool.js';

/**
 * Canonical Charter KPIs defined by the Frozen Acceptance Report (docs/acceptance_report.md) & AC-3/AC-4:
 * 
 * The canonical Charter KPI set represents exactly these six dimensions:
 * 
 * 1. `reading_order_acc` (Reading-Order Accuracy):
 *    - Definition: Pairwise reading-order accuracy between predicted element sequences and ground-truth reading order.
 *    - Boundary: Extracted element sequence after topological layout ordering vs ground truth layout sequence.
 *    - Unit & Range: Accuracy [0.0, 1.0].
 *    - Baseline & Target: Baseline 0.720, Target >= 0.900 (Achieved: 1.000).
 *    - Confidence Intervals: 95% bootstrap CI (1,000 resamples), e.g. [1.000, 1.000].
 *    - Source: docs/acceptance_report.md Section 4 (KPI-1) & Section 5.
 * 
 * 2. `table_structure_fidelity` (Table Structure Fidelity):
 *    - Definition: Tree Edit Distance based Similarity (TEDS) / 2D cell adjacency F1 score capturing table structure and hierarchical relations.
 *    - Boundary: Table structure extraction and cell adjacency graph vs ground truth table structures.
 *    - Unit & Range: F1 / TEDS score [0.0, 1.0].
 *    - Baseline & Target: Baseline 0.600, Target >= 0.850 (Achieved: 1.000).
 *    - Confidence Intervals: 95% bootstrap CI (1,000 resamples), e.g. [1.000, 1.000].
 *    - Source: docs/acceptance_report.md Section 4 (KPI-2) & Section 5.
 * 
 * 3. `downstream_retrieval_acc` (Downstream Retrieval Accuracy):
 *    - Definition: End-to-end grounded retrieval & synthesis quality evaluated across gold chunk hit rates, answer grounding, and multi-rater synthesis rubrics.
 *    - Boundary: End-to-end multi-modal query retrieval, chunk ranking, and grounded synthesis pipeline.
 *    - Unit & Range: Rubric score [0.0, 100.0].
 *    - Baseline & Target: Baseline 38.5 / 100, Target >= 75.0 / 100 (Achieved: 87.1 / 100).
 *    - Confidence Intervals: 95% bootstrap CI (1,000 resamples), e.g. [79.4, 93.7].
 *    - Source: docs/acceptance_report.md Section 4 (KPI-3), Section 5, & Section 7.
 * 
 * 4. `critical_scene_failure_rate` (Critical-Scene Failure Rate):
 *    - Definition: Proportion of critical compliance mandates, financial/benchmark tables, and negative stress cases (NT1–NT5) that fail silently without explicit degraded route flagging or abstention.
 *    - Boundary: Negative anomaly and critical scene audit pipeline (NT1 through NT5: reading gutters, scrambled tables, ungrounded retrieval, partition leaks, workload limits).
 *    - Unit & Range: Rate [0.0, 1.0].
 *    - Baseline & Target: Baseline 0.0, Target = 0.0 (Zero Silent Failures invariant).
 *    - Confidence Intervals: Exact proportion or bootstrap CI, e.g. [0.0, 0.0].
 *    - Source: docs/acceptance_report.md Section 3 (NT1–NT5) & Section 5 (Critical Cases).
 * 
 * 5. `cross_condition_gap` (Cross-Condition Performance Gap):
 *    - Definition: Performance discrepancy / degradation gap observed between the reference baseline arm (O2 baseline) and the candidate provenance-enriched arm (O2 + O3 Final) across critical evaluation dimensions.
 *    - Boundary: Parity evaluation across warm trials comparing baseline and candidate system variants under identical workloads.
 *    - Unit & Range: Absolute delta [0.0, 1.0].
 *    - Baseline & Target: Baseline 0.0, Target <= 0.05.
 *    - Confidence Intervals: Absolute difference [lower_delta, upper_delta].
 *    - Source: docs/acceptance_report.md Section 6 (Parity Evaluation, AC-4).
 * 
 * 6. `inference_latency_ms` (Inference Latency at p95):
 *    - Definition: End-to-end 95th percentile query retrieval and inference latency under warm benchmark workload.
 *    - Boundary: Measured strictly at the end-to-end query retrieval boundary (from query input to ranked results returned).
 *      Subsystem-level operations (e.g. raw FAISS index distance calculations or index builds) MUST NOT be substituted
 *      for `inference_latency_ms`. They belong under `implementation.faiss_search_ms`.
 *    - Unit & Range: Milliseconds (ms) [0.0, +inf).
 *    - Baseline & Target: Baseline 15.00 ms, Target < 5.00 ms (Achieved: 1.37 ms).
 *    - Statistical Reconciliation Audit (M1.5.4):
 *      In `docs/acceptance_report.md`, the reported point estimate `1.37 ms` represents the 95th percentile (p95)
 *      across 270 warm queries (30 warm trials x 9 acceptance questions).
 *      The reported interval `[0.77, 0.83] ms` was generated by `calculate_bootstrap_ci()` in `eval/metrics.py`,
 *      which resampled the arithmetic sample mean (mean ~ 0.80 ms, CI [0.77, 0.83] ms), NOT the 95th percentile.
 *      Therefore, `[0.77, 0.83] ms` is the bootstrap CI of the sample mean, and must NOT be presented or stored
 *      as the measured confidence interval of the p95 statistic. If retained for audit continuity, it must be
 *      explicitly classified as illustrative or labeled under its true statistic ('mean') to prevent misattribution.
 *    - Source: docs/acceptance_report.md Section 4 (KPI-6), Section 5, & Section 6; eval/run_acceptance.py.
 * 
 * SEPARATE IMPLEMENTATION METRICS:
 * Subsystem and implementation-specific metrics (e.g. `formula_extraction_match_rate`, `audit_lineage_coverage`,
 * `faiss_search_ms`, `cache_hit_rate`, `peak_rss_mb`) are classified as separate implementation metrics and
 * MUST NOT overwrite or be substituted for Charter KPI dimensions.
 */
export const CHARTER_KPI_KEYS = Object.freeze([
  'reading_order_acc',
  'table_structure_fidelity',
  'downstream_retrieval_acc',
  'critical_scene_failure_rate',
  'cross_condition_gap',
  'inference_latency_ms',
]);

export const IMPLEMENTATION_METRIC_KEYS = Object.freeze([
  'formula_extraction_match_rate',
  'audit_lineage_coverage',
  'faiss_search_ms',
  'cache_hit_rate',
  'peak_rss_mb',
  'index_build_ms',
]);

/**
 * Validates a Charter KPI set against canonical requirements.
 * Ensures:
 * - Implementation metrics cannot reside in or overwrite the charter KPI namespace.
 * - Missing charter metrics cannot be silently replaced by implementation metrics.
 * 
 * @param {Object} charterObj - Map of charter KPIs
 * @param {Object} [options]
 * @param {boolean} [options.requireAll=false] - Whether all 6 canonical KPIs must be present
 * @returns {boolean} True if valid
 */
export function validateCharterKpiSet(charterObj, options = {}) {
  if (!charterObj || typeof charterObj !== 'object') {
    throw new Error('Charter KPIs must be an object.');
  }

  // Prevent implementation metrics from invading charter namespace
  for (const key of Object.keys(charterObj)) {
    if (key === 'confidence_intervals') continue;
    if (IMPLEMENTATION_METRIC_KEYS.includes(key)) {
      throw new Error(
        `Invalid charter KPI '${key}': this is an implementation metric and cannot overwrite or reside in the charter namespace.`
      );
    }
    if (!CHARTER_KPI_KEYS.includes(key)) {
      throw new Error(`Unknown metric '${key}' in charter namespace.`);
    }
  }

  if (options.requireAll) {
    for (const key of CHARTER_KPI_KEYS) {
      if (!(key in charterObj)) {
        throw new Error(
          `Missing required canonical charter KPI '${key}'. Implementation metrics cannot be substituted for missing charter dimensions.`
        );
      }
    }
  }

  return true;
}

/**
 * Formats structured KPI metrics ensuring Charter KPIs and implementation-specific
 * telemetry are stored in dedicated, isolated namespaces.
 * 
 * Enforces:
 * - Charter KPIs are validated and kept separate from implementation metrics.
 * - Formula extraction and audit lineage cannot overwrite critical scene failure rate or cross-condition gap.
 * - Raw benchmark data and bootstrap confidence intervals are preserved without loss.
 * 
 * @param {Object} options
 * @param {Object} [options.charter={}] - Core acceptance charter KPIs
 * @param {Object} [options.implementation={}] - Implementation-specific operational metrics (e.g. formula_extraction_match_rate, faiss_search_ms, peak_rss_mb)
 * @param {Object} [options.confidence_intervals={}] - Optional 95% bootstrap confidence intervals
 * @param {Object} [options.raw=null] - Raw unaggregated benchmark measurements and sample counts
 * @returns {Object} Structured KPI entity
 */
export function formatKpiPayload({
  charter = {},
  implementation = {},
  confidence_intervals = {},
  raw = null,
} = {}) {
  // Validate that implementation metrics are not smuggled into the charter namespace
  validateCharterKpiSet(charter);

  const formattedCharter = {};
  for (const [k, v] of Object.entries(charter)) {
    if (CHARTER_KPI_KEYS.includes(k)) {
      formattedCharter[k] = v;
    }
  }

  return {
    charter: {
      ...formattedCharter,
      ...(confidence_intervals && Object.keys(confidence_intervals).length > 0 ? { confidence_intervals } : {}),
    },
    implementation: {
      ...implementation,
    },
    ...(raw !== null && raw !== undefined ? { raw } : {}),
  };
}

/**
 * Normalizes an evaluation run row from MySQL into a domain entity.
 */
function mapEvalRunRow(row) {
  if (!row) return null;

  const parseJson = (val) => {
    if (!val) return null;
    return typeof val === 'string' ? JSON.parse(val) : val;
  };

  return {
    id: Number(row.id),
    config_hash: row.config_hash,
    model_versions: parseJson(row.model_versions),
    split: row.split,
    dataset_split_hash: row.dataset_split_hash || null,
    acceptance_hash: row.acceptance_hash || null,
    kpi: parseJson(row.kpi),
    status: row.status,
    created_at: row.created_at,
  };
}

/**
 * Records a completed evaluation run with full provenance.
 * 
 * @param {Object} runData
 * @param {string} runData.config_hash - SHA-256 hash of configuration
 * @param {Object} runData.model_versions - Version metadata for models
 * @param {string} runData.split - Split name (e.g. 'ac3', 'dev')
 * @param {string} [runData.dataset_split_hash] - SHA-256 hash of dataset split manifest
 * @param {string} [runData.acceptance_hash] - SHA-256 hash of acceptance criteria / harness
 * @param {Object} runData.kpi - Measured KPI metrics (e.g. extraction_f1, reading_order_acc)
 * @param {string} [runData.status='completed'] - Run status
 * @returns {Promise<Object>} Created evaluation record
 */
export async function createRun(runData) {
  if (!runData.config_hash || typeof runData.config_hash !== 'string' || runData.config_hash.length > 64) {
    throw new Error('config_hash is required and must not exceed 64 characters.');
  }
  if (runData.dataset_split_hash && runData.dataset_split_hash.length > 64) {
    throw new Error('dataset_split_hash must not exceed 64 characters.');
  }
  if (runData.acceptance_hash && runData.acceptance_hash.length > 64) {
    throw new Error('acceptance_hash must not exceed 64 characters.');
  }
  if (!runData.model_versions || typeof runData.model_versions !== 'object') {
    throw new Error('model_versions is required and must be an object.');
  }
  if (!runData.split || typeof runData.split !== 'string') {
    throw new Error('split is required and must be a string.');
  }
  if (!runData.kpi || typeof runData.kpi !== 'object') {
    throw new Error('kpi is required and must be an object.');
  }

  const sql = `
    INSERT INTO eval_runs (
      config_hash, model_versions, split, dataset_split_hash, acceptance_hash, kpi, status
    ) VALUES (?, ?, ?, ?, ?, ?, ?)
  `;

  const params = [
    runData.config_hash,
    JSON.stringify(runData.model_versions),
    runData.split,
    runData.dataset_split_hash || null,
    runData.acceptance_hash || null,
    JSON.stringify(runData.kpi),
    runData.status || 'completed',
  ];

  try {
    const [result] = await query(sql, params);
    return await findById(result.insertId);
  } catch (err) {
    throw sanitizeError(err);
  }
}

/**
 * Finds an evaluation run by its numeric ID.
 * 
 * @param {number|string} id
 * @returns {Promise<Object|null>}
 */
export async function findById(id) {
  const numericId = Number(id);
  if (!Number.isInteger(numericId) || numericId <= 0) return null;

  const [rows] = await query(`SELECT * FROM eval_runs WHERE id = ? LIMIT 1`, [numericId]);
  return rows.length > 0 ? mapEvalRunRow(rows[0]) : null;
}

/**
 * Lists evaluation runs with optional filtering and pagination.
 * 
 * @param {Object} [options]
 * @param {number} [options.limit=50]
 * @param {number} [options.offset=0]
 * @param {string} [options.split]
 * @param {string} [options.config_hash]
 * @param {string} [options.status]
 * @returns {Promise<{runs: Array<Object>, total: number, limit: number, offset: number}>}
 */
export async function listRuns(options = {}) {
  const limit = Math.max(1, Math.min(Number(options.limit) || 50, 500));
  const offset = Math.max(0, Number(options.offset) || 0);

  const whereClauses = [];
  const params = [];

  if (options.split) {
    whereClauses.push('split = ?');
    params.push(options.split);
  }

  if (options.config_hash) {
    whereClauses.push('config_hash = ?');
    params.push(options.config_hash);
  }

  if (options.status) {
    whereClauses.push('status = ?');
    params.push(options.status);
  }

  const whereSql = whereClauses.length > 0 ? `WHERE ${whereClauses.join(' AND ')}` : '';

  const countSql = `SELECT COUNT(*) AS total FROM eval_runs ${whereSql}`;
  const [countRows] = await query(countSql, params);
  const total = Number(countRows[0]?.total || 0);

  const selectSql = `
    SELECT * FROM eval_runs
    ${whereSql}
    ORDER BY id DESC
    LIMIT ? OFFSET ?
  `;

  const [rows] = await query(selectSql, [...params, limit, offset]);

  return {
    runs: rows.map(mapEvalRunRow),
    total,
    limit,
    offset,
  };
}

/**
 * Gets the most recent evaluation run, optionally filtered by split.
 * 
 * @param {string} [split=null] - Optional split name
 * @returns {Promise<Object|null>}
 */
export async function getLatestRun(split = null) {
  const whereClauses = [];
  const params = [];

  if (split) {
    whereClauses.push('split = ?');
    params.push(split);
  }

  const whereSql = whereClauses.length > 0 ? `WHERE ${whereClauses.join(' AND ')}` : '';
  const sql = `
    SELECT * FROM eval_runs
    ${whereSql}
    ORDER BY id DESC
    LIMIT 1
  `;

  const [rows] = await query(sql, params);
  return rows.length > 0 ? mapEvalRunRow(rows[0]) : null;
}
